import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../lib/pluginPackage";

/**
 * `npm run cards:earth-mask`: rasterizes Aion's bundled world (Natural Earth 1:50m, public domain — the same data as its
 * maps) into the land mask the Earth–Moon card colours its Earth from, and writes it as run lengths into
 * src/cards/apps/earthMoon/landMask.ts. Reproducible: the same data always gives the same file.
 *
 * Equirectangular, 2048 × 1024; row 0 is 90° N, column 0 is 180° W. Each row is a list of alternating run lengths
 * (ocean first) as unsigned LEB128 varints; all rows concatenated and base64-encoded.
 */
const WIDTH = 2048, HEIGHT = 1024;
const world = JSON.parse(readFileSync(join(REPO_ROOT, "src/host/geo/world-data.json"), "utf8")) as { regions: { polygons: number[][][] }[] };
const mask = new Uint8Array(WIDTH * HEIGHT);

/** Rings decode from [x0, y0, dx1, dy1, …] in hundredths of a degree into pixel coordinates. */
function decode(ring: number[]): [number, number][] {
  const points: [number, number][] = [];
  let x = 0, y = 0;
  for (let i = 0; i < ring.length; i += 2) {
    x = i === 0 ? ring[0] : x + ring[i]; y = i === 0 ? ring[1] : y + ring[i + 1];
    points.push([(x / 100 + 180) / 360 * WIDTH, (90 - y / 100) / 180 * HEIGHT]);
  }
  return points;
}

// Even-odd scanline fill of each polygon (outer ring and holes together), OR-ed into the mask.
for (const region of world.regions) {
  for (const polygon of region.polygons) {
    const rings = polygon.map(decode);
    let top = HEIGHT, bottom = 0;
    for (const ring of rings) for (const [, py] of ring) { top = Math.min(top, py); bottom = Math.max(bottom, py); }
    for (let row = Math.max(0, Math.floor(top)); row <= Math.min(HEIGHT - 1, Math.ceil(bottom)); row++) {
      const y = row + 0.5, crossings: number[] = [];
      for (const ring of rings) for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i], [xj, yj] = ring[j];
        if ((yi > y) !== (yj > y)) crossings.push(xi + (y - yi) * (xj - xi) / (yj - yi));
      }
      crossings.sort((a, b) => a - b);
      for (let k = 0; k + 1 < crossings.length; k += 2) {
        for (let col = Math.max(0, Math.ceil(crossings[k] - 0.5)); col <= Math.min(WIDTH - 1, Math.floor(crossings[k + 1] - 0.5)); col++) mask[row * WIDTH + col] = 1;
      }
    }
  }
}
// Antarctica's outline ends at its coast: everything south of it is ice-covered land.
for (let row = Math.round(HEIGHT * (1 - 12 / 180)); row < HEIGHT; row++) mask.fill(1, row * WIDTH, (row + 1) * WIDTH);

const bytes: number[] = [];
const varint = (value: number) => { do { let b = value & 0x7f; value >>>= 7; if (value) b |= 0x80; bytes.push(b); } while (value); };
let land = 0;
for (let row = 0; row < HEIGHT; row++) {
  let value = 0, run = 0;
  for (let col = 0; col < WIDTH; col++) {
    const v = mask[row * WIDTH + col];
    land += v;
    if (v === value) run++;
    else { varint(run); value = v; run = 1; }
  }
  varint(run);
}
const data = Buffer.from(bytes).toString("base64");
writeFileSync(join(REPO_ROOT, "src/cards/apps/earthMoon/landMask.ts"), `/**
 * Earth's land mask for the Earth–Moon card, generated by \`npm run cards:earth-mask\` (scripts/cards/earth-mask.ts) from
 * Natural Earth 1:50m (public domain, https://www.naturalearthdata.com) — Aion's bundled world. Do not edit by hand.
 * Equirectangular ${WIDTH} × ${HEIGHT}; rows of alternating run lengths (ocean first), unsigned LEB128, base64.
 * Land: ${(land / mask.length * 100).toFixed(1)} % of the pixels.
 */
export const LAND_MASK = { width: ${WIDTH}, height: ${HEIGHT}, data: "${data}" } as const;
`);
console.log(`landMask.ts: ${WIDTH}×${HEIGHT}, ${(data.length / 1024).toFixed(0)} KB, land ${(land / mask.length * 100).toFixed(1)} %`);
