/**
 * Validates every model catalogue the plugin ships (v0.9) and writes the readable catalogue, docs/MODEL-CATALOGUE.md:
 * what Aion can show now (bundled), what is only referenced (catalogued, the user may import it), and what is restricted
 * (suspected game rips, never imported). Fails on an invalid manifest, a duplicate, or a bundled file that is missing or
 * does not pass the asset policy.
 *
 *   npm run models:catalogue
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { validateGlb } from "../../src/cards/assets/gltf";
import { modelCatalogue, type ModelManifest } from "../../src/visual/models/manifest";
import { ModelRegistry } from "../../src/visual/models/registry";
import { MODEL_LIBRARY_LIMITS } from "../../src/host/models/library";
import { PLUGIN_ROOT, REPO_ROOT } from "../lib/pluginPackage";

const dir = join(PLUGIN_ROOT, "assets", "models");
const files = ["library.json", ...readdirSync(join(dir, "catalogue")).filter(f => f.endsWith(".json")).sort().map(f => `catalogue/${f}`)];
const all: ModelManifest[] = [];
const problems: string[] = [];
for (const file of files) {
  const parsed = modelCatalogue.safeParse(JSON.parse(readFileSync(join(dir, file), "utf8")));
  if (!parsed.success) { problems.push(`${file}: ${parsed.error.issues[0]?.path.join(".")} ${parsed.error.issues[0]?.message}`); continue; }
  for (const entry of parsed.data.entries) {
    if (entry.file) {
      const path = join(dir, entry.file);
      if (!existsSync(path)) problems.push(`${entry.id}: missing ${entry.file}`);
      else try { validateGlb(new Uint8Array(readFileSync(path)), MODEL_LIBRARY_LIMITS); } catch (error) { problems.push(`${entry.id}: ${String(error)}`); }
    }
    all.push(entry);
  }
}
const registry = new ModelRegistry(all.map(manifest => ({ manifest, installed: Boolean(manifest.file) })));
if (registry.size !== all.length) problems.push(`${all.length - registry.size} ids appear in more than one catalogue`);
for (const group of registry.duplicates()) problems.push(`duplicate source: ${group.join(", ")}`);
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

const bundled = all.filter(e => e.availability === "redistributable");
const references = all.filter(e => e.availability === "catalogued");
const restricted = references.filter(e => e.rights.extractedGameAsset && e.rights.extractedGameAsset !== "no");
const bySubject = new Map<string, ModelManifest[]>();
for (const e of references) bySubject.set(e.subject ?? e.id, [...(bySubject.get(e.subject ?? e.id) ?? []), e]);
const licences = new Map<string, number>();
for (const e of references) licences.set(e.licence.label, (licences.get(e.licence.label) ?? 0) + 1);
const cell = (value: string) => value.replace(/\|/g, "\\|");
const lines = [
  "# Model catalogue",
  "",
  "Generated by `npm run models:catalogue` from the plugin's catalogues (`plugins/aion-presence/assets/models/`). How the",
  "library works and what the states mean: [MODEL-LIBRARY.md](MODEL-LIBRARY.md).",
  "",
  `**${bundled.length} available** (bundled, redistributable) · **${references.length} catalogued references** to ${bySubject.size} characters (no file;`,
  `the user may download one under its terms and import it) · **${restricted.length} restricted** (suspected extracts from commercial games: never imported).`,
  `Checked ${[...new Set(all.map(e => e.checked))].sort().at(-1)}.`,
  "",
  "## Available now",
  "",
  "| Model | Id | Source | Licence | Clips |",
  "| --- | --- | --- | --- | --- |",
  ...bundled.map(e => `| ${e.name} | \`${e.id}\` | [${cell(e.source.title)}](${e.source.url}) by ${cell(e.source.author)} | ${cell(e.licence.label)} | ${e.stats?.animations ? "yes" : "—"} |`),
  "",
  "## Catalogued Pokémon references",
  "",
  "Fan-made models on Sketchfab, found through its public search API. The characters' designs belong to Nintendo /",
  "Creatures Inc. / GAME FREAK inc. (The Pokémon Company); each modeller's licence covers their own work only, so none of",
  "these is redistributable and Aion never downloads them. Download needs a Sketchfab account.",
  "",
  `Licences of the references: ${[...licences].sort((a, b) => b[1] - a[1]).map(([label, count]) => `${label} ${count}`).join(" · ")}.`,
  "",
  "| # | Character | References (author · licence · triangles) |",
  "| --- | --- | --- |",
  ...[...bySubject].map(([, entries]) => {
    const dex = entries[0].aliases?.find(a => /^#\d{4}$/.test(a)) ?? "";
    const refs = entries.map(e => `[${cell(e.source.title)}](${e.source.url}) · ${cell(e.source.author)} · ${e.licence.label}${e.stats?.triangles ? ` · ${e.stats.triangles.toLocaleString("en")}` : ""}${e.rights.extractedGameAsset !== "no" ? " · **restricted**" : ""}`);
    return `| ${dex} | ${entries[0].name} | ${refs.join("<br>")} |`;
  }),
  "",
];
writeFileSync(join(REPO_ROOT, "docs", "MODEL-CATALOGUE.md"), lines.join("\n"));
console.log(`docs/MODEL-CATALOGUE.md: ${bundled.length} available, ${references.length} references (${bySubject.size} characters), ${restricted.length} restricted`);
